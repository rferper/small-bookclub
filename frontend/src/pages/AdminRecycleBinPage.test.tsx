import { act, fireEvent, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import { ApiError, type ApiClient } from '../api/client'
import { createClubState, createEmptyState } from '../api/mock/fixtures'
import { createMockClient } from '../api/mock/mockClient'
import { holdCalls, trackCalls } from '../test/clients'
import { renderApp } from '../test/renderApp'

const BIN = '/administracion/papelera'
const confirm = () => screen.getByRole('button', { name: 'Confirmar eliminación' })

describe('recycle bin routing and reads', () => {
  it('links from Administration, shows the empty state and a return link', async () => {
    const user = userEvent.setup()
    renderApp({ path: '/administracion', client: createMockClient({ state: createEmptyState() }) })
    await user.click(await screen.findByRole('link', { name: 'Papelera' }))
    expect(await screen.findByText(/La papelera está vacía/)).toBeInTheDocument()
    expect(screen.getByRole('link', { name: 'Volver a Administración' })).toHaveAttribute('href', '/administracion')
  })
  it.each(['anonymous', 'denied', 'member', 'curator'] as const)('guards direct bin access for %s before admin reads', async (session) => {
    const tracked = trackCalls(createMockClient({ session }))
    renderApp({ path: BIN, client: tracked.client })
    await screen.findByRole('heading', { level: 1 })
    expect(screen.queryByRole('heading', { name: 'Papelera' })).not.toBeInTheDocument()
    expect(tracked.clubDataCalls()).toEqual([])
  })
  it('shows loading, actionable failure and retry without losing the route', async () => {
    const user = userEvent.setup(), held = holdCalls(createMockClient({ state: createEmptyState(), failures: { getRecycleBin: 1 } }), 'getRecycleBin'), tracked = trackCalls(held.client)
    renderApp({ path: BIN, client: tracked.client })
    await waitFor(() => expect(tracked.calls).toContain('getRecycleBin'))
    expect(screen.getByText('Cargando…')).toBeInTheDocument()
    held.release()
    await user.click(await screen.findByRole('button', { name: 'Reintentar' }))
    expect(await screen.findByText(/La papelera está vacía/)).toBeInTheDocument()
  })
  it('uses mock expiry, retained actor and timestamps; never offers expired restoration', async () => {
    const state = createClubState(), client = createMockClient({ state })
    await client.deleteLiteraryQuote(state.quotes[0].id)
    state.now = state.quotes[0].purgeDueAt!
    renderApp({ path: BIN, client })
    expect(await screen.findByText('El plazo de recuperación ha terminado.')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: /^Restaurar/ })).not.toBeInTheDocument()
    const row = screen.getByRole('button', { name: /^Eliminar definitivamente/ }).closest('li')!
    expect(row).toHaveTextContent('Retirada por:')
    expect(row).toHaveTextContent(state.members.find((m) => m.id === state.quotes[0].deletedBy)!.displayName)
    expect(row).toHaveTextContent('Fin de recuperación:')
    expect(row).toHaveTextContent(state.quotes[0].id)
  })
})

describe('deletion confirmations and source updates', () => {
  it('names a book, previews retained dependencies, cancels via Escape with focus and no mutation, then removes it', async () => {
    const state = createClubState(), api = createMockClient({ state }), tracked = trackCalls(api), user = userEvent.setup()
    const before = JSON.stringify(state), expected = await api.getDeletionPreview('book', 'b1')
    const app = renderApp({ path: '/administracion/libros', client: tracked.client })
    const trigger = await screen.findByRole('button', { name: `Eliminar libro «${state.books[0].title}»` })
    await user.click(trigger)
    const dialog = await screen.findByRole('dialog')
    expect(dialog).toHaveTextContent(expected.label)
    expect(dialog).toHaveTextContent('30 días')
    for (const dependency of expected.dependencies) expect(dialog).toHaveTextContent(dependency)
    expect(within(dialog).getByRole('button', { name: 'Cancelar' })).toHaveFocus()
    await user.tab({ shift: true })
    expect(confirm()).toHaveFocus()
    await user.keyboard('{Escape}')
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
    expect(trigger).toHaveFocus()
    expect(JSON.stringify(state)).toBe(before)
    expect(tracked.calls).not.toContain('deleteBook')
    await user.click(trigger)
    await screen.findByRole('dialog')
    await user.click(confirm())
    await waitFor(() => expect(screen.queryByRole('link', { name: `Editar «${state.books[0].title}»` })).not.toBeInTheDocument())
    await act(() => app.router.navigate(BIN))
    expect(await screen.findByRole('button', { name: `Restaurar ${expected.label}` })).toBeInTheDocument()
    await act(() => app.router.navigate('/biblioteca'))
    await screen.findByRole('heading', { name: 'Biblioteca' })
    expect(screen.queryByRole('link', { name: state.books[0].title })).not.toBeInTheDocument()
  })
  it('retains quote selection/list on pending and failed deletion, permits retry, refreshes after success', async () => {
    const state = createClubState(), user = userEvent.setup(), quote = state.quotes[0]
    const held = holdCalls(createMockClient({ state, failures: { deleteLiteraryQuote: 1 } }), 'deleteLiteraryQuote'), tracked = trackCalls(held.client)
    renderApp({ path: '/administracion/citas', client: tracked.client })
    await user.click(await screen.findByRole('button', { name: `Editar cita: ${quote.text}` }))
    await user.click(screen.getByRole('button', { name: `Eliminar cita «${quote.text}»` }))
    const dialog = await screen.findByRole('dialog')
    await user.click(confirm())
    expect(confirm()).toBeDisabled()
    expect(within(dialog).getByRole('button', { name: 'Cancelar' })).toBeDisabled()
    fireEvent.click(confirm())
    expect(tracked.calls.filter((call) => call === 'deleteLiteraryQuote')).toHaveLength(1)
    held.release()
    expect(await screen.findByRole('alert')).toHaveTextContent('vuelve a intentarlo')
    expect(confirm()).toHaveFocus()
    expect(screen.getByRole('textbox', { name: /^Texto/ })).toHaveValue(quote.text)
    expect(quote.deletedAt).toBeUndefined()
    await user.click(confirm())
    await waitFor(() => expect(screen.queryByRole('button', { name: `Editar cita: ${quote.text}` })).not.toBeInTheDocument())
    expect(screen.getByRole('textbox', { name: /^Texto/ })).toHaveValue('')
  })
  it('meeting editor confirms attendance/summary/highlight/link warnings before removal', async () => {
    const state = createClubState(), client = createMockClient({ state }), user = userEvent.setup()
    const expected = await client.getDeletionPreview('meeting', 'mt1')
    const app = renderApp({ path: '/administracion/reuniones/mt1/editar', client })
    await user.click(await screen.findByRole('button', { name: /^Eliminar reunión del/ }))
    const dialog = await screen.findByRole('dialog')
    for (const dependency of expected.dependencies) expect(dialog).toHaveTextContent(dependency)
    await user.click(confirm())
    await waitFor(() => expect(app.router.state.location.pathname).toBe('/administracion/reuniones'))
    expect(state.meetings.find((m) => m.id === 'mt1')!.deletedAt).toBeDefined()
  })
})

describe('recovery and terminal purge', () => {
  it.each(['restoreDeleted', 'purgeDeleted'] as const)('keeps the last confirmed list on failed %s and blocks duplicate pending actions', async (method) => {
    const state = createClubState(), api = createMockClient({ state }), user = userEvent.setup()
    await api.deleteLiteraryQuote(state.quotes[0].id)
    const before = JSON.stringify(state.quotes), held = holdCalls(createMockClient({ state, failures: { [method]: 1 } }), method), tracked = trackCalls(held.client)
    renderApp({ path: BIN, client: tracked.client })
    await screen.findByRole('button', { name: /^Restaurar/ })
    if (method === 'purgeDeleted') {
      await user.click(screen.getByRole('button', { name: /^Eliminar definitivamente/ }))
      await screen.findByRole('dialog')
    }
    const target = screen.getByRole('button', { name: method === 'purgeDeleted' ? 'Confirmar eliminación definitiva' : /^Restaurar/ })
    await user.click(target)
    expect(target).toBeDisabled()
    fireEvent.click(target)
    expect(tracked.calls.filter((call) => call === method)).toHaveLength(1)
    held.release()
    expect(await screen.findByRole('alert')).toHaveTextContent('Conservamos la lista')
    expect(JSON.stringify(state.quotes)).toBe(before)
    expect(screen.queryByText('Contenido restaurado.')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: /^Restaurar/ })).toBeInTheDocument()
    await user.click(target)
    expect(await screen.findByRole('status')).toHaveTextContent(method === 'purgeDeleted' ? 'Contenido eliminado definitivamente' : 'Contenido restaurado')
  })
  it.each([401, 403])('uses shared session/forbidden handling for recovery failure %s', async (status) => {
    const state = createClubState(), api = createMockClient({ state }), user = userEvent.setup()
    await api.deleteLiteraryQuote(state.quotes[0].id)
    const client: ApiClient = { ...api, restoreDeleted: () => { if (status === 401) state.session = 'anonymous'; return Promise.reject(new ApiError(status, 'Refused')) } }
    renderApp({ path: BIN, client })
    await user.click(await screen.findByRole('button', { name: /^Restaurar/ }))
    expect(await screen.findByRole('heading', { name: status === 403 ? 'Sección reservada' : 'Club de Lectura' })).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: /^Eliminar definitivamente/ })).not.toBeInTheDocument()
  })
  it('restores a quote and refreshes same-session home navigation with its literal text', async () => {
    const state = createEmptyState(), client = createMockClient({ state }), user = userEvent.setup()
    const quote = await client.addLiteraryQuote({ text: '<b>Cita ficticia</b>', author: 'Autora ficticia', source: null, active: true })
    await client.deleteLiteraryQuote(quote.id)
    const app = renderApp({ path: BIN, client })
    await user.click(await screen.findByRole('button', { name: /^Restaurar/ }))
    expect(await screen.findByText('Contenido restaurado.')).toBeInTheDocument()
    expect(screen.getByText(/La papelera está vacía/)).toBeInTheDocument()
    expect(screen.getByRole('heading', { name: 'Contenido retirado' })).toHaveFocus()
    await act(() => app.router.navigate('/'))
    expect(await screen.findByRole('region', { name: 'Una cita para hoy' })).toHaveTextContent('<b>Cita ficticia</b>')
    expect(document.querySelector('b')).toBeNull()
  })
  it('retains the list on restore conflict or purge dependency refusal with actionable messages', async () => {
    const state = createClubState(), client = createMockClient({ state }), user = userEvent.setup()
    await client.deleteBook('b3')
    state.books.find((b) => b.id === 'b2')!.status = 'leyendo'
    renderApp({ path: BIN, client })
    await user.click(await screen.findByRole('button', { name: /^Restaurar/ }))
    expect(await screen.findByRole('alert')).toHaveTextContent(/leyendo|Leyendo/)
    expect(screen.getByRole('button', { name: /^Restaurar/ })).toBeInTheDocument()
    expect(screen.queryByText('Contenido restaurado.')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: /^Eliminar definitivamente/ }))
    await screen.findByRole('dialog')
    await user.click(screen.getByRole('button', { name: 'Confirmar eliminación definitiva' }))
    expect(await screen.findByRole('alert')).toHaveTextContent(/historial|dependencias|conserva/)
    expect(state.books.find((b) => b.id === 'b3')!.deletedAt).toBeDefined()
  })
  it('requires explicit purge confirmation, restores focus on cancel and purges independently', async () => {
    const state = createClubState(), client = createMockClient({ state }), user = userEvent.setup()
    const quote = state.quotes[0]
    await client.deleteLiteraryQuote(quote.id)
    const tracked = trackCalls(client)
    renderApp({ path: BIN, client: tracked.client })
    const trigger = await screen.findByRole('button', { name: /^Eliminar definitivamente/ })
    await user.click(trigger)
    const dialog = await screen.findByRole('dialog')
    expect(dialog).toHaveTextContent(quote.text)
    expect(dialog).toHaveTextContent('dejará de poder recuperarse')
    expect(dialog).toHaveTextContent('no se eliminará en cascada')
    await user.click(within(dialog).getByRole('button', { name: 'Cancelar' }))
    expect(trigger).toHaveFocus()
    expect(tracked.calls).not.toContain('purgeDeleted')
    await user.click(trigger)
    await screen.findByRole('dialog')
    await user.click(screen.getByRole('button', { name: 'Confirmar eliminación definitiva' }))
    expect(await screen.findByText(/Contenido eliminado definitivamente de esta simulación/)).toBeInTheDocument()
    expect(screen.getByText(/La papelera está vacía/)).toBeInTheDocument()
    expect(state.quotes.some((q) => q.id === quote.id)).toBe(false)
  })
  it('preserves a removed meeting reservation during unrelated reading-plan edits and permits explicit unlink', async () => {
    const state = createClubState(), client = createMockClient({ state }), user = userEvent.setup()
    const week = state.weeks.find((w) => w.meetingId === 'mt1')!
    await client.deleteMeeting('mt1')
    renderApp({ path: `/administracion/lecturas/${week.bookId}`, client })
    expect(await screen.findByText('Reunión retirada (vínculo existente)')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: `Editar semana ${week.weekNumber}` }))
    const select = screen.getByRole('combobox', { name: 'Reunión (opcional)' })
    expect(select).toHaveValue('mt1')
    expect(within(select).getByRole('option', { name: 'Reunión retirada (vínculo existente)' })).toBeDisabled()
    fireEvent.change(screen.getByRole('textbox', { name: /^Nota/ }), { target: { value: 'Nota independiente ficticia' } })
    const ack = screen.queryByRole('checkbox', { name: /He revisado/ })
    if (ack) await user.click(ack)
    await user.click(screen.getByRole('button', { name: 'Guardar semana' }))
    await waitFor(() => expect(week.notes).toBe('Nota independiente ficticia'))
    expect(week.meetingId).toBe('mt1')
    await user.click(screen.getByRole('button', { name: `Editar semana ${week.weekNumber}` }))
    await user.selectOptions(screen.getByRole('combobox', { name: 'Reunión (opcional)' }), '')
    const nextAck = screen.queryByRole('checkbox', { name: /He revisado/ })
    if (nextAck) await user.click(nextAck)
    await user.click(screen.getByRole('button', { name: 'Guardar semana' }))
    await waitFor(() => expect(week.meetingId).toBeNull())
  })
})
