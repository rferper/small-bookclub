import { act, fireEvent, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import { ApiError, type ApiClient } from '../api/client'
import { applyRubricExample, createClubState, createEmptyState, emptyRubric } from '../api/mock/fixtures'
import { createMockClient } from '../api/mock/mockClient'
import { holdCalls, trackCalls } from '../test/clients'
import { renderApp } from '../test/renderApp'

const QUOTES = '/administracion/citas', RUBRIC = '/administracion/rubrica'
const text = () => screen.getByRole('textbox', { name: /^Texto/ })
const change = (element: HTMLElement, value: string) => fireEvent.change(element, { target: { value } })
const saveQuote = () => screen.getByRole('button', { name: 'Guardar cita' })

describe('literary admin routing and load states', () => {
  it('links both editors from the hub with a visible return', async () => {
    const user = userEvent.setup()
    renderApp({ path: '/administracion' })
    await user.click(await screen.findByRole('link', { name: 'Citas literarias' }))
    expect(await screen.findByRole('textbox', { name: /^Texto/ })).toBeInTheDocument()
    await user.click(screen.getByRole('link', { name: 'Volver a Administración' }))
    await user.click(await screen.findByRole('link', { name: 'Rúbrica de valoración' }))
    expect(await screen.findByRole('textbox', { name: 'Disfrute: 1 estrella' })).toBeInTheDocument()
    expect(screen.getByRole('link', { name: 'Volver a Administración' })).toHaveAttribute('href', '/administracion')
  })
  it.each(['anonymous', 'denied', 'member', 'curator'] as const)('guards both editor URLs for %s without data calls', async (session) => {
    for (const path of [QUOTES, RUBRIC]) {
      const tracked = trackCalls(createMockClient({ session })), app = renderApp({ path, client: tracked.client })
      await screen.findByRole('heading', { level: 1 })
      expect(screen.queryByRole('textbox')).not.toBeInTheDocument()
      expect(tracked.clubDataCalls()).toEqual([])
      app.unmount()
    }
  })
  it.each([[QUOTES, 'listAdminQuotes'], [RUBRIC, 'getRatingRubric']] as const)('shows loading and retryable load failure at %s', async (path, method) => {
    const user = userEvent.setup(), held = holdCalls(createMockClient({ state: createEmptyState(), failures: { [method]: 1 } }), method), tracked = trackCalls(held.client)
    renderApp({ path, client: tracked.client })
    await waitFor(() => expect(tracked.calls).toContain(method))
    expect(screen.getByText('Cargando…')).toBeInTheDocument()
    held.release()
    await user.click(await screen.findByRole('button', { name: 'Reintentar' }))
    if (path === QUOTES) expect(await screen.findByText(/Todavía no hay citas/)).toBeInTheDocument()
    else expect(await screen.findByRole('textbox', { name: 'Huella: 5 estrellas' })).toHaveValue('')
  })
})

describe('quote forms', () => {
  it('adds literal text with attribution, edits and disables without changing position; homepage reflects navigation', async () => {
    const state = createEmptyState(), user = userEvent.setup(), client = createMockClient({ state }), app = renderApp({ path: QUOTES, client })
    await screen.findByRole('textbox', { name: /^Texto/ })
    expect(screen.getByRole('checkbox', { name: 'Activa en Inicio' })).toBeChecked()
    change(text(), '  <b>Cita ficticia</b>\nsegunda línea  ')
    change(screen.getByRole('textbox', { name: /^Autor/ }), ' Autora ficticia ')
    change(screen.getByRole('textbox', { name: /^Fuente/ }), ' Fuente ficticia ')
    await user.click(saveQuote())
    expect(await screen.findByText('Cambios guardados.')).toBeInTheDocument()
    const quote = state.quotes[0]
    expect(screen.getByText('<b>Cita ficticia</b> segunda línea', { selector: 'p' })).toBeInTheDocument()
    expect(document.querySelector('b')).toBeNull()
    await act(() => app.router.navigate('/'))
    const card = await screen.findByRole('region', { name: 'Una cita para hoy' })
    expect(card).toHaveTextContent('<b>Cita ficticia</b> segunda línea')
    expect(card).toHaveTextContent('Autora ficticia, Fuente ficticia')
    await act(() => app.router.navigate(QUOTES))
    await user.click(await screen.findByRole('button', { name: /^Editar cita:/ }))
    change(text(), 'Texto corregido / literal')
    await user.click(screen.getByRole('checkbox', { name: 'Activa en Inicio' }))
    await user.click(saveQuote())
    await screen.findByText('Cambios guardados.')
    expect(state.quotes[0]).toMatchObject({ id: quote.id, text: 'Texto corregido / literal', active: false })
    expect(screen.getByText('Inactiva')).toBeInTheDocument()
    expect(screen.getAllByRole('button', { name: /Eliminar cita/ })).toHaveLength(1)
    await act(() => app.router.navigate('/'))
    await screen.findByRole('heading', { name: 'Inicio' })
    expect(screen.queryByRole('region', { name: 'Una cita para hoy' })).not.toBeInTheDocument()
  })
  it.each([['text', ''], ['text', 'x'.repeat(1001)], ['author', 'x'.repeat(201)], ['source', 'x'.repeat(201)]] as const)('makes no mutation call for invalid %s', async (name, value) => {
    const tracked = trackCalls(createMockClient()), user = userEvent.setup()
    renderApp({ path: QUOTES, client: tracked.client })
    await screen.findByRole('textbox', { name: /^Texto/ })
    change(text(), 'Nueva cita ficticia')
    change(name === 'text' ? text() : screen.getByRole('textbox', { name: name === 'author' ? /^Autor/ : /^Fuente/ }), value)
    await user.click(saveQuote())
    expect(await screen.findByRole('alert')).toHaveTextContent('Revisa el texto')
    expect(text()).toHaveAccessibleDescription(/Revisa el texto/)
    expect(tracked.calls).not.toContain('addLiteraryQuote')
  })
  it('keeps failed save input and list, suppresses success and duplicate pending submits, then retries', async () => {
    const state = createClubState(), before = JSON.stringify(state.quotes), user = userEvent.setup()
    const held = holdCalls(createMockClient({ state, failures: { addLiteraryQuote: 1 } }), 'addLiteraryQuote'), tracked = trackCalls(held.client)
    renderApp({ path: QUOTES, client: tracked.client })
    await screen.findByRole('textbox', { name: /^Texto/ })
    change(text(), 'Texto de prueba que se conserva')
    await user.click(saveQuote())
    expect(screen.getByRole('button', { name: 'Guardando…' })).toBeDisabled()
    fireEvent.submit(text().closest('form')!)
    expect(tracked.calls.filter((call) => call === 'addLiteraryQuote')).toHaveLength(1)
    held.release()
    expect(await screen.findByRole('alert')).toHaveTextContent('vuelve a intentar guardar')
    expect(text()).toHaveValue('Texto de prueba que se conserva')
    expect(screen.queryByText('Cambios guardados.')).not.toBeInTheDocument()
    expect(JSON.stringify(state.quotes)).toBe(before)
    await user.click(saveQuote())
    await screen.findByText('Cambios guardados.')
    expect(state.quotes).toHaveLength(3)
  })
  it.each([400, 404, 409])('announces understandable save refusal %s without clearing input', async (status) => {
    const api = createMockClient(), client: ApiClient = { ...api, addLiteraryQuote: () => Promise.reject(new ApiError(status, status === 409 ? 'Ya existe una cita con este texto.' : status === 404 ? 'Esta cita ya no está disponible.' : 'Revisa el texto.')) }
    const user = userEvent.setup()
    renderApp({ path: QUOTES, client })
    await screen.findByRole('textbox', { name: /^Texto/ })
    change(text(), 'Contenido conservado')
    await user.click(saveQuote())
    expect(await screen.findByRole('alert')).not.toBeEmptyDOMElement()
    expect(text()).toHaveValue('Contenido conservado')
    expect(screen.queryByText('Cambios guardados.')).not.toBeInTheDocument()
  })
})

describe('rubric form', () => {
  it('has 25 blank fields grouped in order, saves/clears all atomically and rating navigation shows whole/half anchors', async () => {
    const state = createClubState(), user = userEvent.setup(), app = renderApp({ path: RUBRIC, client: createMockClient({ state }) })
    await screen.findByRole('textbox', { name: 'Huella: 5 estrellas' })
    expect(screen.getAllByRole('textbox')).toHaveLength(25)
    expect(screen.getAllByRole('textbox').every((field) => (field as HTMLTextAreaElement).value === '')).toBe(true)
    expect(screen.getAllByRole('group').map((group) => group.querySelector('legend')?.textContent)).toEqual(['Disfrute', 'Estilo', 'Personajes', 'Trama', 'Huella'])
    change(screen.getByRole('textbox', { name: 'Estilo: 4 estrellas' }), '  <b>Anclaje ficticio cuatro</b>\nliteral  ')
    change(screen.getByRole('textbox', { name: 'Estilo: 5 estrellas' }), 'Anclaje ficticio cinco')
    change(screen.getByRole('textbox', { name: 'Huella: 3 estrellas' }), '   ')
    await user.click(screen.getByRole('button', { name: 'Guardar rúbrica completa' }))
    await screen.findByText('Cambios guardados.')
    expect(state.rubric.estilo[4]).toBe('<b>Anclaje ficticio cuatro</b>\nliteral')
    expect(state.rubric.huella[3]).toBeNull()
    await act(() => app.router.navigate('/biblioteca/b2/valorar'))
    const group = await screen.findByRole('group', { name: 'Estilo' })
    expect(group).toHaveTextContent('Anclaje ficticio cuatro')
    expect(group).toHaveTextContent('Anclaje ficticio cinco')
    expect(group.querySelector('b')).toBeNull()
    await user.click(within(group).getByRole('radio', { name: '4 estrellas' }))
    expect(group).not.toHaveTextContent('Anclaje ficticio cinco')
    await act(() => app.router.navigate(RUBRIC))
    const four = await screen.findByRole('textbox', { name: 'Estilo: 4 estrellas' })
    change(four, '')
    await user.click(screen.getByRole('button', { name: 'Guardar rúbrica completa' }))
    await screen.findByText('Cambios guardados.')
    expect(state.rubric.estilo[4]).toBeNull()
  })
  it('does not submit placeholders/default invented text and keeps only existing marked dev examples', async () => {
    const state = applyRubricExample(createClubState()), user = userEvent.setup()
    renderApp({ path: RUBRIC, client: createMockClient({ state }) })
    const one = await screen.findByRole('textbox', { name: 'Disfrute: 1 estrella' })
    expect(one).toHaveValue('')
    expect(screen.getByRole('textbox', { name: 'Disfrute: 2 estrellas' })).toHaveValue('[Texto de ejemplo] Disfrute, 2 estrellas')
    await user.click(screen.getByRole('button', { name: 'Guardar rúbrica completa' }))
    await screen.findByText('Cambios guardados.')
    expect(state.rubric.disfrute[1]).toBeNull()
  })
  it('refuses overlong fields without a call, then keeps all typed data through failed save and pending double submit', async () => {
    const state = createClubState(), user = userEvent.setup(), held = holdCalls(createMockClient({ state, failures: { saveRatingRubric: 1 } }), 'saveRatingRubric'), tracked = trackCalls(held.client)
    renderApp({ path: RUBRIC, client: tracked.client })
    const last = await screen.findByRole('textbox', { name: 'Huella: 5 estrellas' })
    change(last, 'x'.repeat(501))
    await user.click(screen.getByRole('button', { name: 'Guardar rúbrica completa' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('500')
    expect(tracked.calls).not.toContain('saveRatingRubric')
    change(last, 'Typed anchor')
    await user.click(screen.getByRole('button', { name: 'Guardar rúbrica completa' }))
    expect(screen.getByRole('button', { name: 'Guardando…' })).toBeDisabled()
    fireEvent.submit(last.closest('form')!)
    expect(tracked.calls.filter((call) => call === 'saveRatingRubric')).toHaveLength(1)
    held.release()
    expect(await screen.findByRole('alert')).toHaveTextContent('vuelve a intentar guardar')
    expect(last).toHaveValue('Typed anchor')
    expect(state.rubric).toEqual(emptyRubric())
    expect(screen.queryByText('Cambios guardados.')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Guardar rúbrica completa' }))
    await screen.findByText('Cambios guardados.')
    expect(state.rubric.huella[5]).toBe('Typed anchor')
  })
  it.each([QUOTES, RUBRIC])('uses shared forbidden/session behavior on save at %s', async (path) => {
    for (const status of [403, 401]) {
      const state = createClubState(), api = createMockClient({ state })
      const refuse = () => { if (status === 401) state.session = 'anonymous'; return Promise.reject(new ApiError(status, 'Refused')) }
      const client: ApiClient = { ...api, addLiteraryQuote: refuse, saveRatingRubric: refuse }, user = userEvent.setup()
      const app = renderApp({ path, client })
      if (path === QUOTES) { await screen.findByRole('textbox', { name: /^Texto/ }); change(text(), 'Test') }
      else await screen.findByRole('textbox', { name: 'Huella: 5 estrellas' })
      await user.click(screen.getByRole('button', { name: path === QUOTES ? 'Guardar cita' : 'Guardar rúbrica completa' }))
      expect(await screen.findByRole('heading', { name: status === 403 ? 'Sección reservada' : 'Club de Lectura' })).toBeInTheDocument()
      expect(screen.queryByRole('textbox')).not.toBeInTheDocument()
      app.unmount()
    }
  })
})
