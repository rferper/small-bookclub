import { fireEvent, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it } from 'vitest'
import { createClubState } from '../api/mock/fixtures'
import { createMockClient } from '../api/mock/mockClient'
import { holdCalls, trackCalls } from '../test/clients'
import { renderApp } from '../test/renderApp'

const path = '/administracion/reuniones/mt1/resumen'
const change = (name: string, value: string) => fireEvent.change(screen.getByLabelText(name), { target: { value } })
describe('admin meeting record editor', () => {
  it.each(['member', 'curator'] as const)('guards the direct path for %s without reads', async (session) => {
    const tracked = trackCalls(createMockClient({ session }))
    renderApp({ path, client: tracked.client })
    await screen.findByRole('heading', { name: 'Sección reservada' }); expect(tracked.clubDataCalls()).toEqual([])
  })
  it('links calendar/edit routes, retries load, identifies unread and removed weeks and unknown meetings', async () => {
    const user = userEvent.setup(), state = createClubState(), api = createMockClient({ state, failures: { getAdminMeetingRecord: 1 } })
    const app = renderApp({ path: '/administracion/reuniones/mt2/editar', client: api })
    await user.click(await screen.findByRole('link', { name: 'Editar resumen y momentos destacados' }))
    await screen.findByText('No se ha podido cargar el resumen.')
    await user.click(screen.getByRole('button', { name: 'Reintentar' }))
    expect(await screen.findByLabelText('Texto del resumen')).toHaveValue(state.meetings.find((m) => m.id === 'mt2')!.summary!.text)
    expect(screen.queryByRole('button', { name: 'Marcar como segura' })).not.toBeInTheDocument()
    app.unmount(); await api.removeReadingWeek('b3','w1')
    const removed = renderApp({ path, client: api })
    expect(await screen.findByText(/Semana retirada:/)).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Marcar como segura' })).not.toBeInTheDocument()
    removed.unmount(); renderApp({ path: '/administracion/reuniones/unknown/resumen' })
    expect(await screen.findByRole('heading', { name: 'No encontramos esta reunión' })).toBeInTheDocument()
  })
  it('retains input and confirmed preview after failed saves, prevents duplicate calls and renders literal text', async () => {
    const user = userEvent.setup(), api = createMockClient({ failures: { saveMeetingSummary: 1 } }), held = holdCalls(api, 'saveMeetingSummary'), tracked = trackCalls(held.client)
    renderApp({ path, client: tracked.client }); await screen.findByLabelText('Texto del resumen')
    const text = '<script>nunca ejecutar</script>\n**texto literal**'
    change('Texto del resumen', text)
    await user.click(screen.getByRole('button', { name: 'Guardar resumen' }))
    expect(screen.getByRole('button', { name: 'Guardar resumen' })).toBeDisabled()
    fireEvent.submit(screen.getByLabelText('Texto del resumen').closest('form')!)
    expect(tracked.calls.filter((m) => m === 'saveMeetingSummary')).toHaveLength(1)
    held.release(); expect(await screen.findByRole('alert')).toHaveTextContent('Error simulado')
    expect(screen.getByLabelText('Texto del resumen')).toHaveValue(text)
    expect(screen.queryByText(text)).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Guardar resumen' }))
    expect(await screen.findByText(text, { selector: 'p', exact: true, normalizer: (s) => s })).toBeInTheDocument()
    expect(document.querySelector('main script')).toBeNull()
    change('Texto del resumen', ' '); await user.click(screen.getByRole('button', { name: 'Guardar resumen' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('resumen vacío')
  })
  it('adds, edits and publishes highlights independently, retains failed order and focuses the moved item', async () => {
    const user = userEvent.setup(), state = createClubState(), api = createMockClient({ state, failures: { reorderMeetingHighlights: 1 } })
    renderApp({ path, client: api }); await screen.findByLabelText('Texto del momento')
    change('Texto del momento', '  Nuevo\n<b>literal</b>  ')
    await user.selectOptions(screen.getByLabelText('Tipo'), 'paraphrase')
    await user.click(screen.getByLabelText('Momento publicado'))
    await user.click(screen.getByRole('button', { name: 'Guardar momento' }))
    await screen.findByRole('heading', { name: 'Momento 5 · Paráfrasis · Publicado' })
    expect(screen.getByLabelText('Texto del momento')).toHaveFocus()
    await user.click(screen.getByRole('button', { name: 'Subir momento 5' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Error simulado')
    expect(screen.getByRole('heading', { name: 'Momento 5 · Paráfrasis · Publicado' })).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Subir momento 5' }))
    await screen.findByRole('heading', { name: 'Momento 4 · Paráfrasis · Publicado' })
    expect(screen.getByRole('button', { name: 'Editar momento 4' })).toHaveFocus()
    await user.click(screen.getByRole('button', { name: 'Editar momento 4' }))
    expect(screen.getByLabelText('Texto del momento')).toHaveValue('Nuevo\n<b>literal</b>')
    await user.click(screen.getByLabelText('Momento publicado')); await user.click(screen.getByRole('button', { name: 'Guardar momento' }))
    await screen.findByRole('heading', { name: 'Momento 4 · Paráfrasis · Borrador' })
    expect(state.meetings.find((m) => m.id === 'mt1')!.summary!.published).toBe(true)
  })
  it('confirms retained removal and safe visibility with keyboard cancellation, then refreshes member navigation', async () => {
    const user = userEvent.setup(), state = createClubState(), api = createMockClient({ state })
    const app = renderApp({ path, client: api }); await screen.findByRole('button', { name: 'Quitar momento 1' })
    await user.click(screen.getByRole('button', { name: 'Quitar momento 1' }))
    expect(screen.getByRole('dialog')).toHaveTextContent('30 días')
    expect(within(screen.getByRole('dialog')).getByRole('button', { name: 'Cancelar' })).toHaveFocus()
    await user.keyboard('{Escape}'); expect(screen.getByRole('button', { name: 'Quitar momento 1' })).toHaveFocus()
    expect(state.meetings.find((m) => m.id === 'mt1')!.highlights[0].deletedAt).toBeUndefined()
    await user.click(screen.getByRole('button', { name: 'Quitar momento 1' })); await user.click(screen.getByRole('button', { name: 'Confirmar retirada' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    expect(screen.getByLabelText('Texto del momento')).toHaveFocus()
    expect(state.meetings.find((m) => m.id === 'mt1')!.highlights[0].deletedAt).toBe(state.now)
    app.unmount()
    renderApp({ path: '/administracion/reuniones/mt6/resumen', client: api })
    await user.click(await screen.findByRole('button', { name: 'Marcar como segura' }))
    await user.click(screen.getByRole('button', { name: 'Cancelar' })); expect(state.meetings.find((m) => m.id === 'mt6')!.markedSafe).toBe(false)
    await user.click(screen.getByRole('button', { name: 'Marcar como segura' })); await user.click(screen.getByRole('button', { name: 'Confirmar visibilidad segura' }))
    await screen.findByRole('button', { name: 'Deshacer visibilidad segura' })
    await user.click(screen.getByRole('link', { name: 'Reuniones' }))
    await user.click(await screen.findByRole('link', { name: /28 de noviembre de 2024/ }))
    expect(await screen.findByText(/Despedimos «Cumbres/)).toBeInTheDocument()
  })
  it('retains historical speaker choices and entered text when a highlight edit fails', async () => {
    const user = userEvent.setup(), state = createClubState(), api = createMockClient({ state, failures: { updateMeetingHighlight: 1 } })
    await api.revokeMember('m3')
    renderApp({ path, client: api })
    await user.click(await screen.findByRole('button', { name: 'Editar momento 1' }))
    const historical = screen.getByLabelText('Carmen (atribución histórica, sin acceso)')
    expect(historical).toBeChecked()
    change('Texto del momento', 'Edición pendiente\n<script>literal</script>')
    await user.click(screen.getByRole('button', { name: 'Guardar momento' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Error simulado')
    expect(screen.getByLabelText('Texto del momento')).toHaveValue('Edición pendiente\n<script>literal</script>')
    expect(screen.getByText('Vetusta no es una ciudad, es un estado de ánimo.')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Guardar momento' }))
    expect(await screen.findByText('Edición pendiente\n<script>literal</script>', { selector: 'p', normalizer: (s) => s })).toBeInTheDocument()
    expect(state.meetings.find((m) => m.id === 'mt1')!.highlights[0].speakerIds).toEqual(['m3'])
    expect(screen.queryByLabelText('Carmen (atribución histórica, sin acceso)')).not.toBeInTheDocument()
  })
  it('keeps failed confirmed removals and safe changes retryable without changing saved state', async () => {
    const user = userEvent.setup(), state = createClubState(), api = createMockClient({ state, failures: { removeMeetingHighlight: 1, setMeetingRecordSafe: 1 } })
    const app = renderApp({ path, client: api })
    await user.click(await screen.findByRole('button', { name: 'Quitar momento 1' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar retirada' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Error simulado')
    expect(state.meetings.find((m) => m.id === 'mt1')!.highlights[0].deletedAt).toBeUndefined()
    await user.click(screen.getByRole('button', { name: 'Confirmar retirada' }))
    await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
    app.unmount(); renderApp({ path: '/administracion/reuniones/mt6/resumen', client: api })
    await user.click(await screen.findByRole('button', { name: 'Marcar como segura' }))
    await user.click(screen.getByRole('button', { name: 'Confirmar visibilidad segura' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Error simulado')
    expect(state.meetings.find((m) => m.id === 'mt6')!.markedSafe).toBe(false)
    await user.click(screen.getByRole('button', { name: 'Confirmar visibilidad segura' }))
    await user.click(await screen.findByRole('button', { name: 'Deshacer visibilidad segura' }))
    await screen.findByRole('button', { name: 'Marcar como segura' })
    expect(state.meetings.find((m) => m.id === 'mt6')!.markedSafe).toBe(false)
  })
})
